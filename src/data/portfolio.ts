// Function to calculate initial values for portfolio
export function initializePortfolio(): StockHolding[] {
  const totalInvestment = initialPortfolioData.reduce(
    (sum, stock) => sum + stock.purchasePrice * stock.quantity,
    0
  );

  return initialPortfolioData.map((stock) => {
    const investment = stock.purchasePrice * stock.quantity;
    return {
      ...stock,
      investment,
      portfolioPercentage: (investment / totalInvestment) * 100,
      cmp: null,
      presentValue: null,
      gainLoss: null,
      gainLossPercentage: null,
      peRatio: null,
      latestEarnings: null,
      isLoading: true,
      error: null,
    };
  });
}
